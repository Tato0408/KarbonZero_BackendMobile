  CREATE TABLE "TBSERVICES"
   (	"IDSERVICE" RAW(16),
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	 PRIMARY KEY ("IDSERVICE")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBTRANSPORTCONSUMPTION"
   (	"IDTRANSPORTCONSUMPTION" RAW(16),
	"IDTRANSPORT" RAW(16) NOT NULL ENABLE,
	"IDUSER" RAW(16) NOT NULL ENABLE,
	"DISTANCE" NUMBER NOT NULL ENABLE,
	"CONSUMPTIONDATE" DATE NOT NULL ENABLE,
	"LATITUDE" NUMBER,
	"LONGITUDE" NUMBER,
	 CHECK (distance > 0 AND distance < 40075.017) ENABLE,
	 PRIMARY KEY ("IDTRANSPORTCONSUMPTION")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBTRANSPORTS"
   (	"IDTRANSPORT" RAW(16),
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	"CARBONFOOTPRINT" NUMBER NOT NULL ENABLE,
	 CHECK (carbonFootprint >0) ENABLE,
