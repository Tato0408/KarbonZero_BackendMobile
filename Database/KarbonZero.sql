	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	 PRIMARY KEY ("IDMEASURE")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBMEASUREUNITS"
   (	"IDMEASUREUNIT" RAW(16),
	"IDMEASURE" RAW(16) NOT NULL ENABLE,
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	 PRIMARY KEY ("IDMEASUREUNIT")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBMEASUREUNITSSERVICES"
   (	"IDMEASUREUNITSERVICE" RAW(16),
	"IDSERVICE" RAW(16) NOT NULL ENABLE,
	"IDMEASUREUNIT" RAW(16) NOT NULL ENABLE,
