  CREATE TABLE "TBCARS"
   (	"IDCAR" RAW(16),
	"IDUSER" RAW(16) NOT NULL ENABLE,
	"IDCARSIZE" RAW(16) NOT NULL ENABLE,
	 PRIMARY KEY ("IDCAR")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBCARSIZES"
   (	"IDCARSIZE" RAW(16),
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	 PRIMARY KEY ("IDCARSIZE")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBCHANNELPOST"
   (	"IDCHANNELPOST" RAW(16),
	"TITLE" VARCHAR2(100) NOT NULL ENABLE,
	"DESCRIPT" VARCHAR2(200) NOT NULL ENABLE,
	"IMAGEPATH" VARCHAR2(100),
	"ISAPPROVED" NUMBER(1,0) DEFAULT 0,
	"IDCHANNEL" RAW(16) NOT NULL ENABLE,
	"IDUSER" RAW(16) NOT NULL ENABLE,
	 CHECK (isApproved IN (0,1)) ENABLE,
	 PRIMARY KEY ("IDCHANNELPOST")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBCHANNELS"
   (	"IDCHANNEL" RAW(16),
	"IDCOMPANY" RAW(16) NOT NULL ENABLE,
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	"DESCRIPT" VARCHAR2(200),
	"IMAGEPATH" VARCHAR2(100),
	 PRIMARY KEY ("IDCHANNEL")
  USING INDEX  ENABLE,
	 UNIQUE ("IDCOMPANY")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBCHANNELSUSERS"
   (	"IDCHANNELUSER" RAW(16),
	"IDCHANNEL" RAW(16) NOT NULL ENABLE,
	"IDUSER" RAW(16) NOT NULL ENABLE,
	 PRIMARY KEY ("IDCHANNELUSER")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBCOMPANIES"
   (	"IDCOMPANY" RAW(16),
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	"BACKENDDOMAIN" VARCHAR2(200),
	"FRONTENDDOMAIN" VARCHAR2(200),
	"APIKEY" VARCHAR2(200) NOT NULL ENABLE,
	 PRIMARY KEY ("IDCOMPANY")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE,
	 UNIQUE ("BACKENDDOMAIN")
  USING INDEX  ENABLE,
	 UNIQUE ("FRONTENDDOMAIN")
  USING INDEX  ENABLE,
	 UNIQUE ("APIKEY")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBCOUNTRIES"
   (	"IDCOUNTRY" RAW(16),
	"NAME" VARCHAR2(100) NOT NULL ENABLE,
	"CARBONFOOTPRINT" NUMBER NOT NULL ENABLE,
	 CHECK (carbonFootprint >0) ENABLE,
	 PRIMARY KEY ("IDCOUNTRY")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBFOODCATEGORIES"
   (	"IDFOODCATEGORY" RAW(16),
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	"CARBONFOOTPRINT" NUMBER NOT NULL ENABLE,
