	"IDPETTYPE" RAW(16),
	"IDUSER" RAW(16),
	 PRIMARY KEY ("IDUSERPET")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBUSERS"
   (	"IDUSER" RAW(16),
	"IDCOUNTRY" RAW(16),
