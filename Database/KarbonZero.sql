	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBFOODCONSUMPTIONS"
   (	"IDFOODCONSUMPTION" RAW(16),
	"IDUSER" RAW(16) NOT NULL ENABLE,
	"CONSUMPTIONDATE" DATE NOT NULL ENABLE,
	"LATITUDE" NUMBER,
	"LONGITUDE" NUMBER,
	 PRIMARY KEY ("IDFOODCONSUMPTION")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBFOODCONSUMPTIONSFOOD"
