	"IDFOOD" RAW(16) NOT NULL ENABLE,
	"IDFOODCONSUMPTION" RAW(16) NOT NULL ENABLE,
	 PRIMARY KEY ("IDFOODCONSUMPTIONSFOOD")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBFOODS"
   (	"IDFOOD" RAW(16),
	"IDFOODCATEGORY" RAW(16) NOT NULL ENABLE,
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	 PRIMARY KEY ("IDFOOD")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBFRIENDS"
   (	"IDFRIEND" RAW(16),
	"IDUSER1" RAW(16) NOT NULL ENABLE,
	"IDUSER2" RAW(16) NOT NULL ENABLE,
	 PRIMARY KEY ("IDFRIEND")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBFUELCONSUMPTIONS"
   (	"IDFUELCONSUMPTION" RAW(16),
	"IDTYPECAR" RAW(16) NOT NULL ENABLE,
	"QUANTITY" NUMBER NOT NULL ENABLE,
	"CONSUMPTIONDATE" DATE NOT NULL ENABLE,
	"LATITUDE" NUMBER,
	"LONGITUDE" NUMBER,
