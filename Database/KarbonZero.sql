	"DISABLED" NUMBER(1,0) DEFAULT 0 NOT NULL ENABLE,
	"IMAGEPATH" VARCHAR2(200),
	 PRIMARY KEY ("IDUSER")
  USING INDEX  ENABLE,
	 UNIQUE ("USERNAME")
  USING INDEX  ENABLE,
	 UNIQUE ("EMAIL")
  USING INDEX  ENABLE
   ) ;

