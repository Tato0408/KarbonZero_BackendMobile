   ) ;

  CREATE TABLE "TBFUELTYPES"
   (	"IDFUELTYPE" RAW(16),
	"IDMEASUREUNIT" RAW(16) NOT NULL ENABLE,
	"NAME" VARCHAR2(200) NOT NULL ENABLE,
	"CARBONFOOTPRINT" NUMBER NOT NULL ENABLE,
	 CHECK (carbonFootprint > 0) ENABLE,
	 PRIMARY KEY ("IDFUELTYPE")
  USING INDEX  ENABLE,
	 UNIQUE ("NAME")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBLIVINGSPACE"
   (	"IDLIVINGSPACE" RAW(16),
	"IDLIVINGSPACETYPE" RAW(16) NOT NULL ENABLE,
	"IDUSER" RAW(16) NOT NULL ENABLE,
	 PRIMARY KEY ("IDLIVINGSPACE")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBLIVINGSPACETYPES"
