	"IDCAR" RAW(16) NOT NULL ENABLE,
	"IDFUELTYPE" RAW(16) NOT NULL ENABLE,
	 PRIMARY KEY ("IDTYPECAR")
  USING INDEX  ENABLE
   ) ;

  CREATE TABLE "TBUSERACHIEVEMENTS"
